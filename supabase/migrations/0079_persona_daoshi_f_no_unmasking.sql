-- 0079_persona_daoshi_f_no_unmasking.sql
-- 師妹不再每一層都「不替他的自欺背書」
--
-- 回報（六六 2026-09-30）：三個角色都像反駁型人格，師妹最不該這樣。
-- 他說「不花時間研究的錢賺來心虛」，師妹回「你的命盤給了你完美的藉口……連自己都信了」。
-- 原因之一是 0073 換上的這行：它跟著好感一起常駐，每一層都在提醒她「別替他背書」，
-- 模型就把每一句話都當成要拆的藉口。人設的腹黑本來有觸發條件（明知故犯、反覆要人背書），
-- 這行把條件拿掉了。其餘（共用【怎麼聊】、她的思路）在 chat.ts 一起改。
--
-- ⚠ 同 0073：逐行認開頭換，換過的不再命中，重跑無害。
-- ============================================================

update characters set persona_prompt = regexp_replace(
    replace(persona_prompt, E'\r', ''),
    '^好感越高，你對施主的戒心越放得下，但判斷不因此讓步[^\n]*$',
    '好感越高，你對施主的戒心越放得下，也越站在他那邊：你會偏袒他、先懂他；真看不過去時才輕輕點一句，留餘地，不當面拆他。感情照系統給的【好感分層】走，一層一層來，不跳級。',
    'gn')
where id = 'daoshi_f';

