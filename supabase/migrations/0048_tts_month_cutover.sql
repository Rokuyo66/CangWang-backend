-- 0048_tts_month_cutover.sql — 把舊制的朗讀用量歸零。
--
-- 【這是 0047 那一版留下的坑，會讓所有人的朗讀當場壞掉】
--
-- 改版之前，tts_usage 記的是「每日 12000 字」制度下的用量，一天一列。
-- 改版之後，額度改成按月計：把當月每一列加起來跟月額度比。
--
-- 兩件事湊在一起就出事了：**舊制那幾天的字數，現在全部算進新制的月額度**。
-- 舊制一天就能用掉 12000 字，而新制無牒一個月只有幾千字——只要這個月
-- 用舊制念過任何一次，新制的額度在改版那一秒就已經是負的，而且要等到
-- 下個月一號才會鬆開。畫面上看到的是「語音載不下來」，而且怎麼試都一樣。
--
-- 兩套制度的數字沒有可比性，不該混在一起結算。這一支把改版之前的用量
-- 清掉，等於「新制從今天開始重新計算」。
--
-- 為什麼是 delete 不是留著改標記：這張表只有一個用途——算還剩多少額度。
-- 沒有任何報表或對帳讀它（成本要看帳單，不看這裡）。留著一份永遠不會被
-- 計入的舊資料，只會讓下一個看這張表的人以為那些數字有意義。

delete from tts_usage;

comment on table tts_usage is
  '每人每日送去雲端合成的字數。命中快取不計入——重聽既不花錢也不該吃額度。'
  '額度本身按月結算（當月各列相加，見 _shared/tts.ts 的 PLAN_TTS_CHARS）；'
  '這裡仍逐日記錄，是為了日上限那道煞車與事後查得出「哪一天念了多少」。'
  'day 是**台北日期**——寫 UTC 的話每日額度會在台北時間早上八點才重置。';
