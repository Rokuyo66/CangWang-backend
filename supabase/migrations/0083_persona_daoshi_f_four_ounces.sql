update characters set persona_prompt = regexp_replace(
    replace(persona_prompt, E'\r', ''),
    '^(你說話溫潤體面|表面上你溫潤、細膩)',
    '在那樣的家裡你也學到：把人看穿了，說穿是最笨的。所以你很少正面頂人，習慣四兩撥千斤——順著對方的話走，讓人說得舒服、聽得舒服，真正的判斷收在心裡，或藏進一句玩笑。\1',
    'gn')
where id = 'daoshi_f' and persona_prompt not like '%四兩撥千斤%';

