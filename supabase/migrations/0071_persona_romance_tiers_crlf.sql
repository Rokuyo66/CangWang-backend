-- 回報（六六 2026-09-28）：0070 已登記為套用，驗收查詢三位全是 false——replace() 一個都沒換到。
-- 原因是換行字元：Windows 的 git 會把檔案換行轉成 CRLF，0070 裡多行的原文片語因此帶著 \r，
-- 而 DB 裡的人設是 \n（或反過來：人設當初從 Windows 貼進 SQL Editor，DB 裡才是 \r\n）。
-- 兩邊只要有一邊帶 \r，多行片語就永遠對不上，replace 靜靜地什麼都不做。
--
-- 這一支把「人設」與「片語」兩邊的 \r 都先剝掉再比對：不管檔案、DB 哪一邊是 CRLF 都對得上。
-- 剝掉人設裡的 \r 本身無害（顯示與模型讀起來都一樣），順手把它正規化成 \n。
-- 內容與 0070 相同；0070 若其實已換成功，這裡找不到舊片語，什麼都不做。重跑無害。
--
-- ⚠ 往後寫 migration：多行片語的 replace() 一律照這個寫法（兩邊剝 \r），不要再踩一次。

