  id         bigint generated always as identity primary key,
  day        date not null default ((now() at time zone 'Asia/Taipei')::date),
  body       text not null check (length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);

-- 只有後端（service role）能讀寫：前端一律走 interpret 的 mail_list。
alter table changelog enable row level security;

create index if not exists changelog_day_idx on changelog (day desc, id desc);
create unique index if not exists changelog_dedupe_idx on changelog (day, md5(body));

