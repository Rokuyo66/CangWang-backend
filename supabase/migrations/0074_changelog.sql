-- 觀中誌・更新日誌（全站一份，不寄信、不亮紅點）
--
-- 更新紀錄與「信」分開（六六 2026-09-29）：
--   · 信（mail）一人一份、亮紅點、可以夾靈石——留給大版本、補償、節慶。
--   · 日誌是全站同一份的流水帳，初期一天可能改好幾次，每次都寄信會把紅點變成雜訊，
--     等真的要發補償時就沒人理了。所以日誌只放著給想看的人翻：信箱「觀中誌」那一格。
--   · 一人一份的信件表也不該拿來存全站同一份的東西：每條日誌 × 全部玩家，只會一直長。
--
-- 寫入：Telegram /log 內文（webhook-tg）。讀取：interpret 的 mail_list 一併帶出。
-- 底下 21 則是原本寫死在談心「觀主頻道」的公告（前端 16c2b42 拿掉前的 ANNOUNCEMENTS），
-- 原文照搬。重跑不會重複（day＋內文雜湊唯一）。
-- ============================================================

