-- 卦案存檔的行動序號：讓「同一局的兩個行動同時寫回」撞得出來，而不是靜靜地少掉一個。
--
-- 洞在哪：一次行動是「讀存檔 → 純函數算出新狀態 → 整包寫回」。兩個請求同時進來，
-- 兩邊都讀到同一份舊狀態，各自算完，後寫的那個把先寫的整包蓋掉——玩家看到的是
-- 「我剛剛明明搜過了，怎麼又沒搜」。手機上這不是理論：點擊重送、離線重試、
-- 切回前景時前端補一次請求，都會製造出兩個同時在飛的行動。
--
-- 修法照舊：讓約束當仲裁者，不做事後比對（同 case_runs_one_active、cast_claims）。
-- 每次寫回都帶「我是根據第 n 號狀態算的」，update 條件加上 seq = n；
-- 撞車的那一個會更新 0 列，服務層據此回「動作重疊了」，而不是覆蓋別人的結果。
--
-- 為什麼是獨立欄位而不是塞在 state 裡：塞在 jsonb 就得用 state->>seq 當過濾條件，
-- 那條路能不能走要看 PostgREST 版本，而且錯了不會報錯——只會每次都比不中、
-- 每個行動都變成「動作重疊」。一個 integer 欄位是確定的。

alter table case_runs add column if not exists seq integer not null default 0;

comment on column case_runs.seq is
  '行動序號，每寫回一次 +1。寫回時以 seq 當樂觀鎖條件，擋掉同一局的併發覆蓋。';
