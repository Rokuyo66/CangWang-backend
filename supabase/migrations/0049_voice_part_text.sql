-- 0049_voice_part_text.sql — parts 多存一樣東西：那一段念的字。
--
-- 語音頁的播放器點下去要做四件事：換成暫停、把念的字攤開來、進度跟著跑、
-- 說得出還剩幾秒。前三件都要「那一段念的是哪些字」，而客戶端手上沒有原文
-- （它從頭到尾只送 cast_id，念什麼由伺服器決定——見 _shared/tts.ts 的檔頭），
-- 所以字只能由收藏這一列帶下去。
--
-- 這一支不動結構：parts 是 jsonb，多一個鍵不必改欄位。改的是註解，
-- 因為註解是這張表唯一寫得下「這個陣列裡有什麼」的地方。
--
-- 舊的列不必補資料：字算得回來（快取鍵就是由原文算的），開語音頁時
-- 由 voice.ts 的 backfillTexts 一次補幾則、補完寫回去，自己會補完。
-- 用 SQL 補不了——要重跑一次分軌與切段，那是 TypeScript 那一側的事。

comment on column voice_clips.parts is
  '[{url, path, chars, narrator, text}, …]，照播放順序。指向 tts bucket 的共用快取；'
  '刪一則收藏**不刪音檔**——那個檔別的收藏、別人的重聽都可能指著它。'
  'text 是那一段念的字（0047 之前收的沒有，由 backfillTexts 補回來）：'
  '播放器要能把念的字攤開來跟著跑，而客戶端手上沒有原文。';
