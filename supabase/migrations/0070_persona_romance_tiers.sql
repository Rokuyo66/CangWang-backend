-- 0070_persona_romance_tiers.sql — 人設的好感刻度換成道緣四層，拿掉「不告白」的寫死上限
--
-- 回報（六六 2026-09-28）：好感都這麼高了，角色對我還這麼無情；陪伴要靠感情線。
-- 原因兩層：
--   ① 人設的好感刻度還是舊的 0–10／11–20／21–30／31 以上，道緣早就是幾百分——刻度對不上；
--   ② 最高那一層仍寫著「不讓角色突然告白」「不把關照解釋成感情」。
-- 感情怎麼分層、在第幾層，改由程式給（chat.ts 的 ROMANCE_RULE／ROMANCE_TIERS／【目前道緣】），
-- 人設這裡只留各自的人格表現，並指向那張表。程式那側已寫明「人設的舊刻度以分層為準」，
-- 所以本檔沒套上也不會出錯，只是人設裡會留著矛盾的舊字。
--
-- ⚠ 同 0068：用 replace() 只換片語，不整段覆寫 persona_prompt（後台可能手改過）。
--   找不到片語時什麼都不做；換過的不會再命中，重跑無害。檔尾有驗收查詢。

