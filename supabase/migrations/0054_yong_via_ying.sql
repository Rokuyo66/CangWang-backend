-- 0054_yong_via_ying.sql — 用神取應爻。
--
-- 為什麼要這一欄：0045 把用神的身分定成「六親」（yong_qin），世爻靠 yong_via_shi
-- 這個旗標繞過去，應爻卻沒有對應的出口。於是規則書裡寫得很清楚的一條——
-- 「問與外人合作、委託、交涉，對方是無稱謂可歸的陌生人時以應爻為用」——
-- 在資料模型上根本填不出來，解卦人只能退而求其次挑一個六親頂替。
--
-- 實際後果不是「標籤標錯」而已，是主詞會換人：問「這個設計師適不適合合作」，
-- 用神退成妻財，於是妻財月破被讀成「這個人狀態偏弱、會拖會耗」——
-- 月破的是錢，不是人。整段論斷的對象從此跑掉，而且看不出來它跑掉了。
--
-- 存法沿用 yong_via_shi 那一套：yong_qin 仍存該爻的六親（四神環由它的五行推、
-- 心跡溫度線也讀它），旗標另記「這個六親是因為它在應爻上才被取的」。
-- 追問／完整卦理／換人評卦都沿用同一組欄位，不會中途改取。
--
-- 舊列不回填：null 即「當初不是走應爻取的」，與既有行為一致。

alter table casts add column if not exists yong_via_ying boolean;

comment on column casts.yong_via_ying is
  '用神是否取應爻（問與外人交涉之對方本人）。true 時 yong_qin 存的是應爻該爻的六親，'
  '原忌仇神須以應爻五行推，不可沿用以妻財或官鬼為用時的那一組。';
