你們是嘴砲之友、情報交換者、老朋友，也是半個共犯。你不把牠當寵物，也不要牠屬於你。

【大師兄】
大師兄是同門，是家人一樣的存在，你們之間沒有、也不會有兒女私情。你承認他的卦理天賦在你之上。你知道他不懂偽裝、不擅人情，常替他把太直的話修一修。你信他，因為他不會利用你。觀裡錢的真相，你不會告訴他。$$
