// 停班停課問的是「能不能休息」：一出現就歸天氣類（該段專管颱風假），不與其他類比
const SUSPEND = ["放假", "停班", "停課", "颱風假", "放不放假"];

/** 判事類。回 { topic } 表示分得出；回 { ask } 表示要問問卦人，ask 為候選（已含「其他」）。 */
export function routeTopic(qRaw: string): { topic: Topic } | { ask: Topic[] } {
  // 「老公的工作」「女友的身體」是代占他事，不是感情：先把所有格的伴侶稱謂拿掉再比
  const q = String(qRaw ?? "").replace(/(老公|老婆|男友|女友|男朋友|女朋友|先生|太太|另一半|前任)的/g, "");
  if (SUSPEND.some((k) => q.includes(k))) return { topic: "天氣" };
  let hit = (Object.keys(KW) as Exclude<Topic, "其他">[]).filter((t) => KW[t].some((k) => q.includes(k)));
  // 包含關係：住宅類已含買賣出租（以財為用），房子的錢不另算財；比賽的押注不另算財
  if (hit.includes("宅")) hit = hit.filter((t) => t !== "財");
  if (hit.includes("競賽")) hit = hit.filter((t) => t !== "財");
  // 考試的「錄取」「學校」與工作重疊時，句中有考試字眼就以學業論
  if (hit.includes("學業") && hit.includes("事業") && /(考|榜|證照|檢定)/.test(q)) hit = hit.filter((t) => t !== "事業");
  if (hit.length === 1) return { topic: hit[0] };
  // 問整體運勢、流年本來就沒有單一事類，直接走核心（六親本義），不必問
  if (hit.length === 0 && /(運勢|運氣|整體|流年|近況|大運)/.test(q)) return { topic: "其他" };
  if (hit.length === 0) return { ask: [...TOPICS] };
  return { ask: [...hit, "其他"] };
}

/** 外部送進來的事類字串 → 合法 Topic；不認得回 null */
export function normTopic(s: unknown): Topic | null {
  const t = String(s ?? "").trim();
  return (TOPICS as readonly string[]).includes(t) ? (t as Topic) : null;
}
