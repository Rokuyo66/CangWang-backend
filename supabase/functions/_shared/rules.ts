export function parseTagged(text: string) {
  const pick = (tag: string) => {
    const m = text.match(new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`));
    return m ? m[1].trim() : null;
  };
  const sugg = pick("sugg");
  const due = pick("due");
  const reading = text
    .replace(/<sugg>[\s\S]*?<\/sugg>/g, "")
    .replace(/<due>[\s\S]*?<\/due>/g, "")
    .replace(/<cat>[\s\S]*?<\/cat>/g, "")
    .replace(/<digest>[\s\S]*?<\/digest>/g, "")
    .replace(/<yong>[\s\S]*?<\/yong>/g, "")
    .trim();
  // 用神：解卦人依角色表取定後回報，存檔供追問／完整卦理沿用同一用神。
  // 只認六親名與「世爻」「應爻」「全盤」，其餘雜訊一律視為未取定（回 null，後續照舊不帶用神提示）。
  // 世／應要先於六親比對：模型常寫成「應爻（父母）」，先掃六親會把它當成一般的父母為用，
  // 而父母兩現時鎖到的往往不是應爻那一爻——問的人就會被換成另一個人。
  //
  // 「全盤」＝解卦人判定此問無單一成敗所繫（格局題、狀態題、多線無主從），刻意不取單一用神。
  // 它與「沒認出來」落到同一個 null 上，是有意的：兩者對下游的要求本來就一樣——
  // 不釘用神提示、追問與展開照精簡版的論述走、溫度線退回世爻。多開一個欄位去分辨
  // 「刻意不取」與「沒取到」，換不到任何一處不同的行為，只會多一個要維護的狀態。
  const yongRaw = pick("yong");
  const QIN = ["父母", "兄弟", "官鬼", "妻財", "子孫"];
  const yong = yongRaw
    ? (yongRaw.includes("全盤") ? null
      : yongRaw.includes("世爻") ? { qin: null as string | null, viaShi: true, viaYing: false }
      : yongRaw.includes("應爻") ? { qin: null as string | null, viaShi: false, viaYing: true }
      : QIN.includes(yongRaw) ? { qin: yongRaw, viaShi: false, viaYing: false }
      : (QIN.find((q) => yongRaw.includes(q)) ? { qin: QIN.find((q) => yongRaw.includes(q))!, viaShi: false, viaYing: false } : null))
    : null;
  return {
    reading,
    suggested: sugg ? sugg.split("|").map((s) => s.trim()).filter(Boolean).slice(0, 3) : [],
    due: due && /^\d{4}-\d{2}-\d{2}$/.test(due) ? due : null,
    category: pick("cat"),
    digest: pick("digest"),
    yong,
  };
}

