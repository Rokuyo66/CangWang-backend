【旺衰】月令定旺相休囚死（與月令同五行者旺、月令所生者相、生月令者休、剋月令者囚、月令所剋者死；辰戌丑未月土旺）。月沖用神=月破（休囚靜爻近乎無用，待出月填實逢合）。日辰力大：生剋沖合值。日沖旺靜爻=暗動（有用）；沖休囚爻=日破。日合=合起或合絆（待沖開）。旬空分真假（本爻、變爻、伏神皆判，盤面已標「空」）：日、月其一旺相者為假空——暫時隱伏、蓄勢待發，暫不受生剋沖合，得日合威力更強（待出空填實沖空而應）；日、月均休囚者為真空——徹底無力，不受任何生剋沖合，得日合仍真空、主虛情假意，其動化只有意念。本爻已真空者，其變爻論沖脫——僅有想法而無行動，不必展開論述。入墓（亥子墓辰、寅卯墓未、巳午墓戌、申酉墓丑；**辰戌丑未為土，土不入墓**）：**前提是該爻在日月休囚——旺相之爻不入墓，唯休囚（休囚死）之爻才被關**。用神、原神、忌神、世應、動爻皆檢；型態：入日墓（爻支墓於日辰）、入月墓、入動墓（動爻兩現、其一入墓於另一墓庫動爻）、入化墓（動爻自化入墓）。墓中之爻如遭封存，不能生剋他爻、亦暫不受生剋沖，主隱藏困住受限制。出墓：動爻沖墓、未來逢年月日時沖開庫、入墓之爻化回頭沖，皆可出；月破之爻入墓於日辰不算入墓；休囚又靜空之爻入墓於日辰，難出。**月墓（入月墓）為短期環境之滯：問極短期（今日、明日）可視情況不論；問中長期則點出「會卡一陣，但大環境長遠不同」。** 問財：財入庫可為聚財；但**問股票投資，財入庫非聚財、乃套牢住套房、動彈不得**，依問事判。絕處逢生主轉機。
【動變】唯動爻（及暗動、出伏之爻）能生剋他爻；旺動力大衰動力小。本爻論現在，變爻論未來變化的趨勢。變爻只對本位動爻生剋沖合，作用過本位動爻即不及旁爻；動爻不可反過來作用自己的變爻；伏神、旁爻不能對變爻有任何作用。化象：回頭生吉、回頭剋凶、化進神力增、化退神力減（進退神僅限同五行相鄰：寅化卯、巳化午、申化酉、亥化子、丑辰未戌順行為進，逆行為退；異五行不論進退）、化合主絆住、化空破墓絕待時方應、化回頭沖屬反吟主事情劇變。多動爻注意彼此生剋與通關鏈。
【沖合大於生剋·總綱】同一爻同時涉沖合與生剋，先論沖合、再論生剋：被合絆之爻暫不受生剋、也暫不生剋他爻，待沖開方行；被沖破之爻生剋不及。【救應】動爻（或用神）逢沖、逢剋而無救者，自身受制，其變爻亦無力回天（回頭生、化進亦難施展）；有救之條件——被剋須有他爻來生（通關生扶）、被沖須有他爻來合（合住解沖）方解。凡救應之合涉及月建，須依所論事物之時效性決定該不該論此短期之合：日辰效力最大，月建效力最低、一般擺最後才論，短期之事月建之合往往可略。細則：動爻與他爻相沖論勝負（旺者勝）；日辰、月建合爻皆主順利而絆住（日合力大於月合）；動爻可合住他爻使其被絆。回頭沖之解沖：唯「日合動爻」解力最佳，日合變爻解力微乎其微；旁爻發動合化動爻、伏神出伏合化動爻、月建合化動爻皆不能解沖，論先合後沖。先沖後合＝事將敗而後成；先合後沖＝先成後敗。六沖遇凶事反主沖散為吉；六沖化六沖為大凶之兆；六合化六合一路順遂；合有宜不宜，過合反為拖延累贅。總吉凶仍取決於用神好壞——沖合定過程聚散，用神定成敗。
【三合局】亥卯未木、寅午戌火、巳酉丑金、申子辰水，成局則成群結黨力量強大，以合化五行論對用神之生剋。僅內卦初三爻動、外卦四上爻動、或三爻以上動可能成局（第三字由日建、月建或變爻補）；單一動爻無三合。成局須同時滿足：局內動爻無化回頭剋、無化回頭沖、日辰不沖局內動爻與變爻（月破不算沖）、他爻不來沖局——其一不滿即破局，破局者縱得日或他爻生扶亦不再成。局中有旬空、月破者，待填實之月日成局。盤面「三合檢核」行為排盤程式所判，以之為準。
【全靜卦·無動爻·必檢】六爻俱靜（無老陽老陰、全盤無動爻）時不可只說「卦象安靜宜守」草草帶過，須：①先掃暗動——日辰沖某旺相靜爻即為暗動，視同發動、能生剋他爻並定吉凶與應期，務必檢查用神與關鍵爻有無被日辰沖起；②無暗動則純就用神靜態旺衰、世應生剋、日月對用神之沖合生剋論斷；③應期取用神逢值、逢沖、填實、或合處逢沖之時。全靜卦的關鍵動態常就藏在暗動與用神旺衰，絕不可漏。
