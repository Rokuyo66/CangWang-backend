export function parseTagged(text: string) {
  const pick = (tag: string) => {
    const m = text.match(new RegExp(`<${tag}>([\\s\\S]*?)</${tag}>`));
    return m ? m[1].trim() : null;
  };
  const sugg = pick("sugg");
  const due = pick("due");
  const reading = text
    .replace(/<sugg>[\s\S]*?<\/sugg>/g, "")
    .replace(/<due>[\s\S]*?<\/due>/g, "")
    .replace(/<cat>[\s\S]*?<\/cat>/g, "")
    .replace(/<digest>[\s\S]*?<\/digest>/g, "")
    .replace(/<yong>[\s\S]*?<\/yong>/g, "")
    .trim();
  // 用神：解卦人依角色表取定後回報，存檔供追問／完整卦理沿用同一用神。
  // 只認六親名與「世爻」，其餘雜訊一律視為未取定（回 null，後續照舊不帶用神提示）。
  const yongRaw = pick("yong");
  const QIN = ["父母", "兄弟", "官鬼", "妻財", "子孫"];
  const yong = yongRaw
    ? (yongRaw.includes("世爻") ? { qin: null as string | null, viaShi: true }
      : QIN.includes(yongRaw) ? { qin: yongRaw, viaShi: false }
      : (QIN.find((q) => yongRaw.includes(q)) ? { qin: QIN.find((q) => yongRaw.includes(q))!, viaShi: false } : null))
    : null;
  return {
    reading,
    suggested: sugg ? sugg.split("|").map((s) => s.trim()).filter(Boolean).slice(0, 3) : [],
    due: due && /^\d{4}-\d{2}-\d{2}$/.test(due) ? due : null,
    category: pick("cat"),
    digest: pick("digest"),
    yong,
  };
}

