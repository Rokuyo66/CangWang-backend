const ZHI = ["子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥"];

// 取籤：等第由卦象決定 → 只在該等第池內選，故籤詩絕不與卦象相反。
// 池內位置由「日辰干支在籤序中的位次」＋「世爻地支序」決定，全確定性、無亂數：
// 同一人同一天同一卦必得同一籤；換日或換卦才換籤。
export function pickQian(tier: QianTier, dayGz: string, shiZhi?: string): Qian {
  const pool = QIAN60.filter((q) => q.tier === tier && q.dayUse !== false);
  const dayN = QIAN60.find((q) => q.gz === dayGz)?.n ?? 1; // 六十甲子皆在譜內，查無僅為防呆
  const zhiN = shiZhi ? ZHI.indexOf(shiZhi) + 1 : 0;
  return pool[(dayN + zhiN) % pool.length];
}
